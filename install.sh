  esac
  printf '\n%s================ VikingAI is installed ================%s\n' "$C_GRN" "$C_RST"
  printf '  Prompt option : %s%s%s\n' "$C_BLD" "$prompt_label" "$C_RST"
  printf '  Model         : %s (via Ollama, %s)\n' "$MODEL" "$OLLAMA_API_BASE"
  printf '  ShellGPT      : %s   LiteLLM: %s\n' "$SGPT_VERSION" "$LITELLM_VERSION"
  if [[ -n "$REPL_FLAG" ]]; then
    printf '  Interactive   : supported (viking --interactive)\n'
  else
    printf '  Interactive   : not supported by this ShellGPT version (single prompts only)\n'

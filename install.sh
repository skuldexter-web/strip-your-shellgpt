#!/usr/bin/env bash
# ==============================================================================
# VikingAI installer
#
# Installs a local, private AI assistant for the terminal:
#   Ollama (local LLM runtime)  +  ShellGPT + LiteLLM (in an isolated Python venv)
#   +  a "viking" role (system prompt)  +  a `viking` launcher command.
#
# Usage:   ./install.sh [options]          (run as a NORMAL user, not root)
#          ./install.sh --help             (all options)
#
# Design decisions worth knowing (details in README.md):
#   * Runs as a normal user; sudo is requested only for apt and the Ollama service.
#   * Ollama is installed with its official installer (https://ollama.com/install.sh),
#     downloaded to a temp file first, checked, then run. Nothing else is fetched
#     from third-party sources.
#   * Python packages live in a private venv (never `sudo pip`).
#   * ShellGPT's global config (~/.config/shell_gpt/.sgptrc) cannot be relocated and
#     may belong to an existing OpenAI-based setup, so VikingAI does NOT edit it.
#     Viking's settings live in ~/.config/vikingai/config.env and are applied by the
#     launcher through environment variables, which ShellGPT itself gives priority
#     over .sgptrc (verified in ShellGPT 1.5.1's config.py).
#   * The system prompt is exclusive: FINAL_SYSTEM_PROMPT is assigned in a `case`
#     from EITHER the custom prompt OR the default prompt. They are never combined.
# ==============================================================================

If 'viking' is "command not found": open a new terminal, or run
  export PATH="$HOME/.local/bin:$PATH"
EXAMPLES_EOF
}

# --- Uninstall ----------------------------------------------------------------
strip_path_block() {
  local rc=$1 tmp
  [[ -f "$rc" ]] && grep -qF "$PATH_MARK_BEGIN" "$rc" || return 0
  tmp=$(mktemp "$TMP_DIR/rc.XXXXXX")
  awk -v b="$PATH_MARK_BEGIN" -v e="$PATH_MARK_END" '$0==b{skip=1;next} $0==e{skip=0;next} !skip' "$rc" >"$tmp"
  cat "$tmp" >"$rc"          # write through, preserving the file's mode/symlink
  ok "Removed PATH block from $rc"
}

do_uninstall() {
  banner
  local role_dir="" model=""
  if [[ -r "$CONFIG_FILE" ]]; then
    local key value
    while IFS='=' read -r key value || [[ -n "$key" ]]; do
      case "$key" in VIKING_ROLE_DIR) role_dir=$value ;; VIKING_MODEL) model=$value ;; esac
    done <"$CONFIG_FILE"
  fi
  log "This removes: the VikingAI venv, the 'viking' launcher, its config/log/cache files, the '$ROLE_NAME' role and the PATH block."
  log "It does NOT remove Ollama, downloaded models, ShellGPT's own config, or your system packages."
  confirm "Remove VikingAI now?" || { log "Cancelled."; exit 0; }

  if [[ -f "$LAUNCHER_PATH" ]] && grep -qF "$LAUNCHER_MARKER" "$LAUNCHER_PATH"; then
    rm -f -- "$LAUNCHER_PATH"; ok "Removed $LAUNCHER_PATH"
  elif [[ -e "$LAUNCHER_PATH" ]]; then
    warn "$LAUNCHER_PATH was not created by VikingAI; left in place."
  fi
  if [[ -n "$role_dir" && -f "$role_dir/$ROLE_NAME.json" ]]; then
    rm -f -- "$role_dir/$ROLE_NAME.json"; ok "Removed role $role_dir/$ROLE_NAME.json"
  fi
  safe_rm_dir "$DATA_DIR" && ok "Removed $DATA_DIR"
  safe_rm_dir "$CONFIG_DIR" && ok "Removed $CONFIG_DIR"
  safe_rm_dir "$STATE_DIR" && ok "Removed $STATE_DIR"
  safe_rm_dir "$HOME/.cache/vikingai" && ok "Removed $HOME/.cache/vikingai"
  strip_path_block "$HOME/.bashrc"
  strip_path_block "$HOME/.zshrc"
  printf '\nVikingAI removed. To also remove Ollama and models (optional):\n'
  [[ -n "$model" ]] && printf '  ollama rm %s\n' "$model"
  printf '  Ollama uninstall steps: https://docs.ollama.com/linux  (section "Uninstall")\n'
  INSTALL_DONE=1
}


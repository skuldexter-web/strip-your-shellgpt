  case "$a" in --help|--version|--list-roles|-lr|--show-role|--list-chats|-lc) needs_api=0 ;; esac
done
if ((needs_api)) && ! curl -fsS --max-time 3 "$VIKING_API_BASE/api/version" >/dev/null 2>&1; then
  die "cannot reach Ollama at $VIKING_API_BASE.
  Start it with:  sudo systemctl start ollama     (or, without systemd:  ollama serve &)"
fi

# ShellGPT's defaults cache prompts/answers in shared /tmp paths (/tmp/cache, /tmp/chat_cache):
# readable by other users on multi-user machines and unusable if another account created them first.
# Keep Viking's conversation data private under ~/.cache/vikingai instead.
cache_root="$HOME/.cache/vikingai"
mkdir -p -m 700 "$cache_root/cache" "$cache_root/chat_cache" 2>/dev/null \
  || die "cannot create cache directory $cache_root"

# Settings for ShellGPT/LiteLLM. Environment variables take priority over ShellGPT's
# ~/.config/shell_gpt/.sgptrc, so an existing OpenAI setup there stays untouched.
# 'ollama_chat/' uses Ollama's /api/chat endpoint (proper system-role support).
# OPENAI_API_KEY is forced to a dummy value: no real key is ever required or sent.
cfg_env=(
  "DEFAULT_MODEL=ollama_chat/$VIKING_MODEL"
  "API_BASE_URL=$VIKING_API_BASE"
  "USE_LITELLM=true"
  "OPENAI_USE_FUNCTIONS=false"
  "OPENAI_API_KEY=ollama-local"
  "ROLE_STORAGE_PATH=$VIKING_ROLE_DIR"
  "CACHE_PATH=$cache_root/cache"
  "CHAT_CACHE_PATH=$cache_root/chat_cache"
  "LITELLM_LOCAL_MODEL_COST_MAP=True"
  "NO_PROXY=localhost,127.0.0.1,::1"
  "no_proxy=localhost,127.0.0.1,::1"
)

if [[ "${VIKING_INHERIT_ENV:-}" == 1 ]]; then
  exec env "${cfg_env[@]}" "$SGPT" --role "$VIKING_ROLE_NAME" ${extra[@]+"${extra[@]}"} "$@"
fi

# Default: run ShellGPT/LiteLLM with a minimal environment, so tokens and keys in
# your shell (AWS_*, GITHUB_TOKEN, SSH_AUTH_SOCK, ...) are not exposed to the Python process.
allow=(PATH HOME USER LOGNAME SHELL TERM COLORTERM LANG LANGUAGE LC_ALL LC_CTYPE LC_MESSAGES TMPDIR EDITOR VISUAL NO_COLOR COLUMNS LINES TZ)
pass_env=()
for v in "${allow[@]}"; do
  if [[ -n "${!v+x}" ]]; then pass_env+=("$v=${!v}"); fi
done
exec env -i "${pass_env[@]}" "${cfg_env[@]}" "$SGPT" --role "$VIKING_ROLE_NAME" ${extra[@]+"${extra[@]}"} "$@"
LAUNCHER_EOF
}

shell_init_files() {
  local f
  for f in "$HOME/.bashrc" "$HOME/.zshrc"; do [[ -f "$f" ]] && printf '%s\n' "$f"; done
  return 0
}

ensure_path() {
  case ":$PATH:" in *":$BIN_DIR:"*) ok "$BIN_DIR is already in PATH"; return 0 ;; esac
  if ((!MODIFY_PATH)); then
    warn "$BIN_DIR is not in PATH (--no-modify-path given). Add it yourself:  export PATH=\"\$HOME/.local/bin:\$PATH\""
    return 0
  fi
  local rc touched=0 files
  files=$(shell_init_files)
  if [[ -z "$files" ]]; then
    case "$(basename -- "${SHELL:-bash}")" in zsh) files="$HOME/.zshrc" ;; *) files="$HOME/.bashrc" ;; esac
  fi
  while IFS= read -r rc; do
    [[ -n "$rc" ]] || continue
    if [[ -f "$rc" ]] && grep -qF "$PATH_MARK_BEGIN" "$rc"; then continue; fi   # idempotent
    {
      printf '\n%s\n' "$PATH_MARK_BEGIN"
      # shellcheck disable=SC2016  # literal backticks in the written comment
      printf '%s\n' '# Added by the VikingAI installer so the `viking` command is found.'
      # shellcheck disable=SC2016  # written literally; expanded when the rc file runs
      printf '%s\n' 'case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) export PATH="$HOME/.local/bin:$PATH" ;; esac'
      printf '%s\n' "$PATH_MARK_END"
    } >>"$rc"
    touched=1
    ok "Added $BIN_DIR to PATH in $rc"
  done <<<"$files"
  ((touched)) && warn "Open a NEW terminal (or run: export PATH=\"\$HOME/.local/bin:\$PATH\") to use the 'viking' command."
  return 0
}

# --- Tests --------------------------------------------------------------------
run_tests() {
  step "13/13" "Testing the installation"
  sgpt_neutral --version >/dev/null 2>&1 || die "Test failed: ShellGPT does not start." "Run: '$SGPT' --version"
  ok "ShellGPT starts"
  api_up || die "Test failed: Ollama API is not reachable at $OLLAMA_API_BASE." \
    "Start it:  sudo systemctl start ollama   (or: ollama serve)"
  ok "Ollama API reachable"
  model_present "$MODEL" || die "Test failed: model '$MODEL' is not available in Ollama." "Run: ollama pull $MODEL"
  ok "Model '$MODEL' is available"
  # Simulate a fresh terminal: minimal env, launcher by absolute path.
  env -i HOME="$HOME" PATH="/usr/bin:/bin" "$LAUNCHER_PATH" --viking-info >/dev/null \
    || die "Test failed: the launcher does not run." "Inspect it: $LAUNCHER_PATH"
  ok "Launcher runs"

  if ((SKIP_TEST)); then warn "End-to-end model test skipped (--skip-test)."; return 0; fi
  info "Asking the model a tiny question (first load can take a minute on slow hardware)..."
  local out="$TMP_DIR/e2e.out" rc=0
  timeout 300 "$LAUNCHER_PATH" --no-md --no-cache "Reply with one short sentence confirming you are working." \
    </dev/null >"$out" 2>"$TMP_DIR/e2e.err" || rc=$?
  if ((rc == 124)); then
    warn "The model did not answer within 300 s. Installation is complete, but this hardware is slow or the model is large."
    warn "Try again later:  viking \"hello\""
    return 0
  fi
  if ((rc != 0)) || [[ ! -s "$out" ]]; then
    cat "$TMP_DIR/e2e.err" >&2 || true
    die "End-to-end test failed (exit code $rc): the model did not return an answer." \
      "Check Ollama:  systemctl status ollama --no-pager   (or: ollama serve)" \
      "Try the model directly:  ollama run $MODEL" \
      "Run the launcher by hand:  viking \"hello\""
  fi
  ok "Model answered: $(head -c 160 "$out" | tr '\n' ' ')"
}


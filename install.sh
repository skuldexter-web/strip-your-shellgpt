# --- Cleanup / traps ----------------------------------------------------------
trap 'LAST_CMD=$BASH_COMMAND; LAST_LINE=$LINENO' ERR

safe_rm_dir() {  # only ever remove directories this installer owns, inside $HOME
  local d=$1
  [[ -n "$d" && "$d" == "$HOME"/?* && -d "$d" && ! -L "$d" ]] || return 1
  rm -rf -- "$d"
}

cleanup() {
  local rc=$?
  trap - ERR
  [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]] && rm -rf -- "$TMP_DIR"
  if ((rc != 0)) && [[ "$INSTALL_DONE" != 1 && "$DO_UNINSTALL" != 1 ]]; then
    if [[ "$EXPLAINED" != 1 ]]; then
      err "Unexpected failure (exit code $rc) near line ${LAST_LINE:-?}: ${LAST_CMD:-?}"
    fi
    # Do not leave a half-built venv behind (config files are written atomically).
    if [[ "$VENV_CREATED_THIS_RUN" == 1 && "$VENV_READY" != 1 ]]; then
      safe_rm_dir "$VENV_DIR" && warn "Removed the incomplete Python environment."
    fi
    err "VikingAI was NOT installed successfully. Nothing above should be treated as a working setup."
    [[ -f "$LOG_FILE" ]] && err "Details: $LOG_FILE"
    err "It is safe to fix the problem and run ./install.sh again."
  fi
}
trap cleanup EXIT
trap 'EXPLAINED=1; err "Interrupted."; exit 130' INT TERM

# --- Small utilities ----------------------------------------------------------
have() { command -v "$1" >/dev/null 2>&1; }

# Append output of a command to the install log while still showing it.
run_logged() {
  { printf '\n$ %s\n' "$*"; } >>"$LOG_FILE"
  "$@" 2>&1 | tee -a "$LOG_FILE"   # pipefail => returns the command's failure
}

# Atomic write: stdin -> temp file in the same directory -> chmod -> rename.
write_atomic() {
  local dest=$1 mode=$2 tmp
  tmp=$(mktemp "$(dirname -- "$dest")/.tmp.XXXXXX")
  if ! cat >"$tmp"; then rm -f -- "$tmp"; return 1; fi
  chmod "$mode" "$tmp"
  mv -f -- "$tmp" "$dest"
}

# ask PROMPT [DEFAULT] -> REPLY_VALUE. Returns 1 on EOF. Non-interactive: default.
ask() {
  local prompt=$1 default=${2-} ans=""
  if [[ -z "$INPUT_FD" ]]; then REPLY_VALUE=$default; return 0; fi
  [[ -n "$default" ]] && prompt+=" [$default]"
  printf '%s: ' "$prompt" >&2
  IFS= read -r -u "$INPUT_FD" ans || return 1
  REPLY_VALUE=${ans:-$default}
}

is_blank() { [[ -z "${1//[[:space:]]/}" ]]; }

# --- Argument parsing ---------------------------------------------------------
need_value() { [[ $# -ge 2 && -n "$2" ]] || die "Option $1 needs a value." "Run ./install.sh --help"; }

parse_args() {
  while (($# > 0)); do
    case "$1" in
      --model)          need_value "$@"; MODEL_ARG=$2; shift 2 ;;
      --model=*)        MODEL_ARG=${1#*=}; shift ;;
      --prompt-mode)    need_value "$@"; PROMPT_MODE_ARG=$2; shift 2 ;;
      --prompt-mode=*)  PROMPT_MODE_ARG=${1#*=}; shift ;;
      --prompt-file)    need_value "$@"; PROMPT_FILE_ARG=$2; shift 2 ;;
      --prompt-file=*)  PROMPT_FILE_ARG=${1#*=}; shift ;;
      --keep-prompt)    KEEP_PROMPT=1; shift ;;
      --non-interactive|--yes|-y) NON_INTERACTIVE=1; shift ;;
      --upgrade)        DO_UPGRADE=1; shift ;;
      --skip-test)      SKIP_TEST=1; shift ;;
      --no-modify-path) MODIFY_PATH=0; shift ;;
      --uninstall)      DO_UNINSTALL=1; shift ;;
      -h|--help)        usage; exit 0 ;;
      *) die "Unknown option: $1" "Run ./install.sh --help" ;;
    esac
  done

  # The two prompt choices are mutually exclusive; reject contradictory flags early.
  case "$PROMPT_MODE_ARG" in ''|custom|default) ;; *) die "--prompt-mode must be 'custom' or 'default'." ;; esac
  if [[ -n "$PROMPT_FILE_ARG" ]]; then
    [[ "$PROMPT_MODE_ARG" != default ]] || die "--prompt-file and --prompt-mode default are mutually exclusive." \
      "Use either your own prompt file OR the default prompt, never both."
    PROMPT_MODE_ARG=custom
  fi
  if ((KEEP_PROMPT)) && [[ -n "$PROMPT_MODE_ARG" ]]; then
    die "--keep-prompt cannot be combined with --prompt-mode/--prompt-file."
  fi
  if [[ "$PROMPT_MODE_ARG" == custom && -z "$PROMPT_FILE_ARG" ]] && ((NON_INTERACTIVE)); then
    die "--prompt-mode custom with --non-interactive needs --prompt-file FILE."
  fi
}

setup_input() {
  # Interactive answers come from the terminal; fall back to /dev/tty when the
  # script itself is piped in; stay non-interactive when there is no terminal.
  ((NON_INTERACTIVE)) && return 0
  if [[ -t 0 ]] || [[ "${VIKING_STDIN_INPUT:-}" == 1 ]]; then
    INPUT_FD=0
  elif ( : </dev/tty ) 2>/dev/null; then
    exec 3</dev/tty
    INPUT_FD=3
  fi
}

# --- Safety: user, sudo, platform ---------------------------------------------
check_not_root() {
  if ((EUID == 0)) && [[ "${VIKING_ALLOW_ROOT:-}" != 1 ]]; then
    die "Please run this installer as a normal user, not as root." \
      "VikingAI installs into your home directory and asks for sudo only when required." \
      "If you really want a root-owned install: VIKING_ALLOW_ROOT=1 ./install.sh"
  fi
}

ensure_sudo() {
  ((SUDO_READY)) && return 0
  if ((EUID == 0)); then
    SUDO_CMD=()
  else
    have sudo || die "sudo is not installed, but this step needs administrator rights." \
      "As root, run:  apt-get install sudo  &&  usermod -aG sudo $USER" \
      "Then log out and back in, and re-run ./install.sh" \
      "Or ask your administrator to install the missing packages for you."
    info "Administrator rights are needed for this step; sudo may ask for your password."
    sudo -v || die "Could not obtain sudo privileges (wrong password, or '$USER' is not in sudoers)." \
      "Ask an administrator to add you to the sudo group (usermod -aG sudo $USER)," \
      "or have them install: curl ca-certificates python3 python3-venv zstd, and Ollama (https://ollama.com/download/linux)."
    SUDO_CMD=(sudo)
  fi
  SUDO_READY=1
}

os_release_field() {
  local key=$1 file
  for file in /etc/os-release /usr/lib/os-release; do
    [[ -r "$file" ]] || continue
    awk -F= -v k="$key" '$1==k{print substr($0,length(k)+2); exit}' "$file" | tr -d "\"'"
    return 0
  done
}

detect_platform() {
  [[ "$(uname -s)" == Linux ]] || die "VikingAI supports Linux only (detected: $(uname -s))."

  DISTRO_ID=$(os_release_field ID)
  local like pretty
  like=$(os_release_field ID_LIKE)
  pretty=$(os_release_field PRETTY_NAME)
  DISTRO_PRETTY=${pretty:-${DISTRO_ID:-unknown}}

  local supported=0
  case "$DISTRO_ID" in
    kali|debian|ubuntu|raspbian|linuxmint|pop|elementary|zorin|neon|devuan|parrot) supported=1 ;;
  esac
  case " $like " in *" debian "*|*" ubuntu "*) supported=1 ;; esac
  ((supported)) || die "Unsupported distribution: $DISTRO_PRETTY" \
    "This installer supports Debian-based systems: Kali, Debian, Ubuntu, Raspberry Pi OS and derivatives." \
    "On other distributions, install Ollama and ShellGPT manually (see README.md, 'Manual install')."
  have apt-get || die "apt-get was not found, so the package manager could not be detected." \
    "This installer needs apt (Debian family)."

  local machine dpkg_arch=""
  machine=$(uname -m)
  have dpkg && dpkg_arch=$(dpkg --print-architecture 2>/dev/null || true)
  case "$machine" in
    x86_64|amd64) ARCH=amd64 ;;
    aarch64|arm64) ARCH=arm64 ;;
    armv6l|armv7l|armhf|i?86)
      die "Unsupported CPU architecture: $machine" \
        "Ollama only publishes 64-bit builds (x86_64 and arm64)." \
        "Raspberry Pi: use a 64-bit Raspberry Pi OS image (Pi 3/4/5/Zero 2 W are 64-bit capable)." ;;
    *) die "Unsupported CPU architecture: $machine" "Ollama supports x86_64 (amd64) and aarch64 (arm64)." ;;
  esac
  case "$dpkg_arch" in
    armhf|armel|i386)
      die "Your kernel is 64-bit but the userland is 32-bit ($dpkg_arch)." \
        "Ollama needs a 64-bit userland. Reinstall with a 64-bit image (e.g. Raspberry Pi OS 64-bit)." ;;
  esac

  if [[ -f /etc/rpi-issue ]] || grep -qs "Raspberry Pi" /proc/device-tree/model 2>/dev/null; then
    IS_RPI=1
  fi
  ok "System: $DISTRO_PRETTY, $ARCH$( ((IS_RPI)) && printf ', Raspberry Pi hardware' )"

  local mem_mb
  mem_mb=$(awk '/^MemTotal:/{print int($2/1024)}' /proc/meminfo 2>/dev/null || echo 0)
  if ((mem_mb > 0 && mem_mb < 2048)); then
    warn "Only ${mem_mb} MB RAM detected. Even the 1.5B default model may be slow or fail to load."
  fi
  if ((IS_RPI)); then
    warn "Raspberry Pi: expect slow responses (CPU only). Stay with small models (<= 1.5B parameters)."
  fi
  if [[ -n "${OLLAMA_HOST:-}" && "$OLLAMA_HOST" != *localhost* && "$OLLAMA_HOST" != *127.0.0.1* ]]; then
    warn "OLLAMA_HOST is set to '$OLLAMA_HOST'. VikingAI talks to $OLLAMA_API_BASE; model pulls here ignore OLLAMA_HOST."
  fi
}

# --- Checks -------------------------------------------------------------------
free_mb() {  # free MB on the filesystem holding $1 (or its nearest existing parent)
  local p=$1
  while [[ ! -d "$p" ]]; do p=$(dirname -- "$p"); done
  df -Pk "$p" | awk 'NR==2{print int($4/1024)}'
}

check_disk() {
  local home_free sys_free
  home_free=$(free_mb "$HOME")
  sys_free=$(free_mb /usr)
  if ((home_free < MIN_FREE_MB_HOME)); then
    die "Not enough free disk space in your home directory: ${home_free} MB (need ${MIN_FREE_MB_HOME} MB)." \
      "Free some space (e.g. 'sudo apt-get clean', remove old files) and re-run."
  fi
  if ! have ollama && ((sys_free < MIN_FREE_MB_SYSTEM)); then
    die "Not enough free disk space for Ollama and a model: ${sys_free} MB on /usr (need ${MIN_FREE_MB_SYSTEM} MB)." \
      "Free some space and re-run. Larger models need several GB more."
  fi
  ok "Disk space: ${home_free} MB free in \$HOME, ${sys_free} MB on /usr"
}

url_reachable() { curl -fsSI --max-time 10 "$1" >/dev/null 2>&1; }

check_internet() {
  have curl || return 0   # curl is installed in the dependency step; re-checked there
  local url
  for url in https://pypi.org https://ollama.com; do
    if url_reachable "$url"; then ok "Internet connectivity ($url reachable)"; return 0; fi
  done
  die "No internet connectivity (could not reach pypi.org or ollama.com)." \
    "Check your network, DNS and proxy settings (https_proxy / http_proxy)." \
    "Test manually:  curl -I https://pypi.org"
}

require_url() {  # require_url URL REASON
  url_reachable "$1" || die "Cannot reach $1 ($2)." \
    "Check your connection/proxy and try again. Test manually:  curl -I $1"
}

python_ok() {
  have python3 && python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)'
}

install_dependencies() {
  local -a need=()
  have curl || need+=(curl)
  dpkg -s ca-certificates >/dev/null 2>&1 || need+=(ca-certificates)
  if have python3; then
    python3 -c 'import ensurepip, venv' >/dev/null 2>&1 || need+=(python3-venv)
  else
    need+=(python3 python3-venv)
  fi
  # Ollama's installer unpacks a .tar.zst archive and needs zstd.
  if ! have ollama && ! have zstd; then need+=(zstd); fi

  if ((${#need[@]} > 0)); then
    info "Installing missing system packages: ${need[*]}"
    ensure_sudo
    if ! run_logged "${SUDO_CMD[@]}" apt-get update; then
      die "'apt-get update' failed." \
        "Check your network and /etc/apt/sources.list; another apt/dpkg process may be holding a lock." \
        "Manual command:  sudo apt-get update"
    fi
    if ! run_logged "${SUDO_CMD[@]}" env DEBIAN_FRONTEND=noninteractive \
        apt-get install -y --no-install-recommends "${need[@]}"; then
      die "Installing system packages failed: ${need[*]}" \
        "Try manually:  sudo apt-get install ${need[*]}" \
        "If dpkg was interrupted:  sudo dpkg --configure -a  &&  sudo apt-get -f install"
    fi
  fi

  # Re-verify: never assume apt did what we asked.
  have curl || die "curl is still missing after installation." "Install it manually: sudo apt-get install curl"
  have python3 || die "python3 is still missing after installation." "Install it manually: sudo apt-get install python3"
  python3 -c 'import ensurepip, venv' >/dev/null 2>&1 || die "Python venv support (python3-venv) is missing." \
    "Install it manually: sudo apt-get install python3-venv"
  python_ok || die "Python 3.9 or newer is required (found: $(python3 --version 2>&1))." \
    "Upgrade your distribution or install a newer Python, then re-run."
  ok "System dependencies present ($(python3 --version 2>&1), curl)"
  if [[ "$(python3 -c 'import sys; print(int(sys.version_info >= (3, 10)))')" != 1 ]]; then
    warn "Python < 3.10: the newest ShellGPT needs 3.10+, so pip may select an older ShellGPT. It is verified below."
  fi
}

# --- Ollama -------------------------------------------------------------------
ollama_cli() { env -u OLLAMA_HOST ollama "$@"; }
api_up() { curl -fsS --max-time 3 "$OLLAMA_API_BASE/api/version" >/dev/null 2>&1; }

confirm() {  # confirm PROMPT -> 0 yes / 1 no. Non-interactive: yes.
  [[ -z "$INPUT_FD" ]] && return 0
  ask "$1 [Y/n]" "" || die "Input closed."
  case "$REPLY_VALUE" in ''|[Yy]|[Yy][Ee][Ss]) return 0 ;; *) return 1 ;; esac
}

install_ollama() {
  if have ollama; then
    ok "Ollama already installed ($(ollama_cli --version 2>&1 | head -n1))"
    return 0
  fi
  require_url https://ollama.com "needed to download Ollama"
  info "Ollama is not installed. VikingAI will use Ollama's OFFICIAL installer:"
  log "    $OLLAMA_INSTALL_URL   (it installs to /usr/local and creates an 'ollama' systemd service)"
  confirm "Download and run the official Ollama installer now?" \
    || die "Ollama is required for VikingAI." "Install it yourself from https://ollama.com/download/linux and re-run."

  ensure_sudo
  local script="$TMP_DIR/ollama-install.sh"
  curl -fsSL --proto '=https' --tlsv1.2 -o "$script" "$OLLAMA_INSTALL_URL" \
    || die "Failed to download the Ollama installer." "Check your connection, then re-run. Docs: https://docs.ollama.com/linux"
  # Sanity check: a non-empty POSIX shell script, not an HTML error page.
  head -n1 "$script" | grep -q '^#!.*sh' && [[ -s "$script" ]] \
    || die "The downloaded Ollama installer does not look like a shell script." \
      "A proxy or captive portal may be interfering. Try again, or install manually: https://docs.ollama.com/linux"
  { printf '\n$ sh %s\n' "$script"; } >>"$LOG_FILE"
  if ! sh "$script" 2>&1 | tee -a "$LOG_FILE"; then
    die "The Ollama installer failed." \
      "Read the output above and $LOG_FILE." \
      "Common causes: missing zstd (sudo apt-get install zstd), no sudo rights, not enough disk space." \
      "Manual install guide: https://docs.ollama.com/linux"
  fi
  hash -r
  have ollama || die "Ollama installation finished but the 'ollama' command was not found." \
    "Open a new terminal or check that /usr/local/bin is in PATH, then re-run ./install.sh"
  ok "Ollama installed ($(ollama_cli --version 2>&1 | head -n1))"
}

has_systemd_unit() {
  have systemctl && [[ -d /run/systemd/system ]] \
    && systemctl list-unit-files ollama.service 2>/dev/null | grep -q '^ollama\.service'
}

ensure_ollama_running() {
  if api_up; then ok "Ollama API is reachable at $OLLAMA_API_BASE"; return 0; fi
  info "Ollama is not responding; starting it..."
  if has_systemd_unit; then
    ensure_sudo
    run_logged "${SUDO_CMD[@]}" systemctl start ollama || true
  else
    warn "No systemd 'ollama' service here (container/WSL/manual install). Starting 'ollama serve' in the background."
    warn "It will NOT restart automatically after a reboot; start it with:  ollama serve"
    ( cd "$HOME" && env -u OLLAMA_HOST setsid nohup ollama serve >>"$STATE_DIR/ollama-serve.log" 2>&1 </dev/null & )
  fi
  local i
  for ((i = 0; i < 40; i++)); do
    api_up && { ok "Ollama API is up at $OLLAMA_API_BASE"; return 0; }
    sleep 1
  done
  if has_systemd_unit; then
    die "Ollama did not become reachable within 40 seconds." \
      "Check the service:  systemctl status ollama --no-pager" \
      "Read its log:       journalctl -u ollama -n 50 --no-pager" \
      "Start it by hand:   sudo systemctl restart ollama   (or: ollama serve)"
  fi
  die "Ollama did not become reachable within 40 seconds." \
    "Read the log:  $STATE_DIR/ollama-serve.log" \
    "Start it by hand in another terminal:  ollama serve"
}

# --- Model selection ----------------------------------------------------------
# Accepts names like: qwen2.5-coder:1.5b, llama3.2:3b, library/name:tag,
# hf.co/user/repo:Q4_K_M. First character must be alphanumeric (no option injection).
valid_model_tag() {
  local t=$1
  ((${#t} <= 200)) || return 1
  case "$t" in ollama/*|ollama_chat/*) return 1 ;; esac   # LiteLLM syntax, not an Ollama tag
  [[ "$t" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*(:[A-Za-z0-9][A-Za-z0-9._-]*)?$ ]]
}

normalize_model_tag() {  # add :latest when no tag is given, as Ollama does
  local t=$1 last=${1##*/}
  [[ "$last" == *:* ]] || t="$t:latest"
  printf '%s' "$t"
}

model_hint() {
  cat <<'HINT_EOF'

  Any model from https://ollama.com/library works, e.g. qwen2.5-coder:1.5b, qwen2.5-coder:7b, llama3.2:3b.
  Requirements depend on YOUR hardware. Rough rule of thumb for 4-bit models: about 1 GB of RAM per
  billion parameters plus overhead. Bigger models need more RAM/VRAM and disk, and are much slower on CPU.
  On a Raspberry Pi or a small VM, stay with the default.
HINT_EOF
}

choose_model() {
  local default=${OLD_MODEL:-$DEFAULT_MODEL_TAG}
  if [[ -n "$MODEL_ARG" ]]; then
    valid_model_tag "$MODEL_ARG" || die "Invalid model tag: '$MODEL_ARG'" \
      "Use the form name[:tag], e.g. qwen2.5-coder:1.5b (no spaces, no 'ollama/' prefix)."
    MODEL=$(normalize_model_tag "$MODEL_ARG")
    return 0
  fi
  if [[ -z "$INPUT_FD" ]]; then MODEL=$(normalize_model_tag "$default"); return 0; fi
  model_hint
  while true; do
    printf '\n' >&2
    ask "Which Ollama model should VikingAI use? (Enter = keep/default)" "$default" || die "Input closed."
    if valid_model_tag "$REPLY_VALUE"; then MODEL=$(normalize_model_tag "$REPLY_VALUE"); return 0; fi
    warn "'$REPLY_VALUE' is not a valid model tag. Use name[:tag] with letters, digits, . _ - (no spaces, no 'ollama/' prefix)."
  done
}

model_present() {
  curl -fsS --max-time 10 "$OLLAMA_API_BASE/api/tags" 2>/dev/null \
    | python3 -c 'import json, sys
names = {m.get("name") for m in json.load(sys.stdin).get("models", [])}
sys.exit(0 if sys.argv[1] in names else 1)' "$1"
}

pull_model() {
  while true; do
    if model_present "$MODEL"; then ok "Model '$MODEL' is already available locally (skipping download)"; return 0; fi
    info "Downloading model '$MODEL' (this can take a while)..."
    local out="$TMP_DIR/pull.out"
    : >"$out"
    if ollama_cli pull "$MODEL" 2>&1 | tee "$out"; then
      model_present "$MODEL" && { ok "Model '$MODEL' downloaded"; return 0; }
      warn "The pull finished but '$MODEL' is not listed by the Ollama API."
    fi
    local reason="The download failed. Check your connection and free disk space (models need GBs)."
    if grep -qiE 'file does not exist|not found|manifest|pull access denied|invalid' "$out"; then
      reason="Ollama does not know the model '$MODEL'. Check the spelling and tag at https://ollama.com/library"
    fi
    err "$reason"
    if [[ -n "$INPUT_FD" && -z "$MODEL_ARG" ]]; then
      ask "Enter another model tag, or press Enter to abort" "" || die "Input closed."
      [[ -n "$REPLY_VALUE" ]] || die "Model download failed; aborting." "Re-run when the model name/connection is fixed: ./install.sh --model <tag>"
      if valid_model_tag "$REPLY_VALUE"; then MODEL=$(normalize_model_tag "$REPLY_VALUE"); else warn "Invalid tag."; fi
      continue
    fi
    die "Model download failed for '$MODEL'." "Try manually:  ollama pull $MODEL" "Then re-run:  ./install.sh --model $MODEL"
  done
}

# --- Python environment -------------------------------------------------------
pkg_version() { "$VENV_DIR/bin/python" -c 'import importlib.metadata as m, sys; print(m.version(sys.argv[1]))' "$1" 2>/dev/null; }

setup_venv() {
  mkdir -p "$DATA_DIR"
  if [[ -x "$VENV_DIR/bin/python" ]] && "$VENV_DIR/bin/python" -c 'import sys' >/dev/null 2>&1; then
    ok "Reusing existing Python environment: $VENV_DIR"
    VENV_READY=1
    return 0
  fi
  if [[ -e "$VENV_DIR" ]]; then
    warn "Existing environment is broken; recreating it."
    safe_rm_dir "$VENV_DIR" || die "Could not remove the broken environment at $VENV_DIR" "Remove it manually and re-run."
  fi
  info "Creating isolated Python environment: $VENV_DIR"
  VENV_CREATED_THIS_RUN=1
  if ! run_logged python3 -m venv "$VENV_DIR"; then
    die "Creating the Python virtual environment failed." \
      "Install venv support:  sudo apt-get install python3-venv" \
      "Then re-run ./install.sh"
  fi
  [[ -x "$VENV_DIR/bin/python" ]] || die "The virtual environment was created without a Python interpreter." "Remove $VENV_DIR and re-run."
  ok "Virtual environment created"
}

check_litellm_not_banned() {
  local v b
  v=$(pkg_version litellm || true)
  for b in "${BANNED_LITELLM_VERSIONS[@]}"; do
    if [[ "$v" == "$b" ]]; then
      EXPLAINED=1
      err "litellm $v is installed in the VikingAI environment. This version was malicious (PyPI supply-chain compromise, 2026-03-24)."
      safe_rm_dir "$VENV_DIR" && err "The environment was deleted."
      die "Treat this machine's credentials (SSH keys, tokens, API keys) as exposed and rotate them." \
        "Then re-run ./install.sh to build a clean environment with a safe litellm version."
    fi
  done
}

install_python_packages() {
  local do_install=0
  if [[ ! -x "$VENV_DIR/bin/sgpt" ]] || ! "$VENV_DIR/bin/python" -c 'import litellm' >/dev/null 2>&1; then
    do_install=1
  fi
  ((DO_UPGRADE)) && do_install=1
  if ((do_install)); then
    require_url https://pypi.org "needed to download ShellGPT and LiteLLM"
    local -a flags=(--disable-pip-version-check --no-input)
    ((DO_UPGRADE)) && flags+=(--upgrade)
    info "Installing ShellGPT + LiteLLM into the virtual environment..."
    # The second requirement excludes the known-malicious litellm releases.
    if ! run_logged "$VENV_DIR/bin/python" -m pip install "${flags[@]}" \
        "shell-gpt[litellm]" "litellm!=1.82.7,!=1.82.8"; then
      die "Installing ShellGPT/LiteLLM with pip failed." \
        "Read the pip output above and $LOG_FILE." \
        "Typical causes: no network/proxy, too-old Python (ShellGPT 1.5 needs 3.10+), full disk." \
        "To start clean:  rm -rf '$VENV_DIR'  &&  ./install.sh"
    fi
  else
    ok "ShellGPT and LiteLLM already installed (use --upgrade to update)"
  fi
  check_litellm_not_banned
  SGPT="$VENV_DIR/bin/sgpt"
  [[ -x "$SGPT" ]] || die "The 'sgpt' executable is missing after installation." "Run: rm -rf '$VENV_DIR' && ./install.sh"
  SGPT_VERSION=$(pkg_version shell-gpt || true)
  LITELLM_VERSION=$(pkg_version litellm || true)
  [[ -n "$SGPT_VERSION" && -n "$LITELLM_VERSION" ]] || die "Could not determine installed ShellGPT/LiteLLM versions."
  VENV_READY=1
  ok "ShellGPT $SGPT_VERSION, LiteLLM $LITELLM_VERSION"
}

# Run sgpt in a clean, neutral environment: no VikingAI overrides, no user secrets.
# The placeholder key only exists to stop ShellGPT's first-run API-key prompt; it is
# never written to disk (ShellGPT skips writing a key that comes from the environment).
sgpt_neutral() {
  env -i HOME="$HOME" PATH="/usr/local/bin:/usr/bin:/bin" LANG="${LANG:-C.UTF-8}" \
    TERM=dumb COLUMNS=250 NO_COLOR=1 OPENAI_API_KEY="viking-local-placeholder" \
    "$SGPT" "$@" </dev/null
}

# ShellGPT's keys/options differ between releases, so inspect the INSTALLED version
# instead of assuming (spec: do not blindly assume keys, role dir or --repl).
probe_shellgpt() {
  local cfgpy key help_text
  cfgpy=$("$VENV_DIR/bin/python" -c 'import importlib.metadata as m
for f in m.files("shell-gpt") or []:
    if str(f).replace("\\", "/").endswith("sgpt/config.py"):
        print(f.locate()); break' 2>/dev/null || true)
  [[ -n "$cfgpy" && -r "$cfgpy" ]] || die "Could not inspect ShellGPT $SGPT_VERSION's configuration module." \
    "Try: ./install.sh --upgrade"
  for key in USE_LITELLM API_BASE_URL OPENAI_USE_FUNCTIONS ROLE_STORAGE_PATH DEFAULT_MODEL OPENAI_API_KEY; do
    # OPENAI_API_KEY is read by name in config.py; the rest are config keys.
    grep -q "\"$key\"" "$cfgpy" || die "ShellGPT $SGPT_VERSION does not use the config key $key that VikingAI relies on." \
      "This ShellGPT version is not supported. Try: ./install.sh --upgrade (needs Python 3.10+)."
  done

  # First run creates ShellGPT's own default config + roles, with NEUTRAL defaults,
  # so VikingAI settings never leak into the shared ~/.config/shell_gpt/.sgptrc.
  sgpt_neutral --version >/dev/null 2>&1 || die "ShellGPT failed to start." \
    "Try running it by hand:  '$SGPT' --version" "Then: ./install.sh --upgrade"

  help_text=$(sgpt_neutral --help 2>&1) || die "'sgpt --help' failed." "Run: '$SGPT' --help"
  grep -q -- '--role' <<<"$help_text" || die "ShellGPT $SGPT_VERSION has no --role option; it is too old/new for VikingAI." \
    "Try: ./install.sh --upgrade"
  if grep -q -- '--repl' <<<"$help_text"; then REPL_FLAG="--repl"; else REPL_FLAG=""; fi

  # Ask ShellGPT itself where its roles live (version-accurate), instead of guessing.
  local first
  first=$(sgpt_neutral --list-roles 2>/dev/null | head -n1 || true)
  if [[ -n "$first" && "$first" == /* ]]; then ROLE_DIR=$(dirname -- "$first"); else ROLE_DIR="$HOME/.config/shell_gpt/roles"; fi
  mkdir -p "$ROLE_DIR"
  [[ -d "$ROLE_DIR" && -w "$ROLE_DIR" ]] || die "ShellGPT's role directory is not writable: $ROLE_DIR"
  [[ "$ROLE_DIR" == "$HOME"/* ]] || warn "ShellGPT's role directory is outside your home: $ROLE_DIR (from your existing ShellGPT config)."
  ok "ShellGPT options detected: --role yes, interactive ${REPL_FLAG:-NOT supported}; role dir: $ROLE_DIR"
}

# --- System prompt selection (mandatory, mutually exclusive) ------------------
load_existing_config() {
  [[ -r "$CONFIG_FILE" ]] || return 0
  local key value
  while IFS='=' read -r key value || [[ -n "$key" ]]; do
    case "$key" in
      VIKING_MODEL) OLD_MODEL=$value ;;
      VIKING_PROMPT_MODE) OLD_PROMPT_MODE=$value ;;
    esac
  done <"$CONFIG_FILE"
}

existing_role_present() { [[ -n "$ROLE_DIR" && -f "$ROLE_DIR/$ROLE_NAME.json" ]]; }

prompt_menu() {  # sets PROMPT_MODE to custom|default
  printf '\n%sChoose your Viking system prompt:%s\n\n' "$C_BLD" "$C_RST" >&2
  printf '  1) Enter my own custom prompt\n  2) Use the default Viking prompt\n\n' >&2
  printf 'The two options are mutually exclusive: exactly ONE prompt is used, never both combined.\n' >&2
  while true; do
    ask "Your choice (1 or 2)" "" || die "Input closed."
    case "$REPLY_VALUE" in
      1) PROMPT_MODE=custom; return 0 ;;
      2) PROMPT_MODE=default; return 0 ;;
      *) warn "Please type 1 or 2." ;;
    esac
  done
}

# Interactive multiline capture. Returns 0 with CUSTOM_PROMPT set, or 10 when the
# user (after an empty submission) explicitly switched to the default option.
read_custom_prompt() {
  local line buf have_data
  while true; do
    printf '\nEnter your system prompt. It is saved EXACTLY as typed (line breaks preserved).\n' >&2
    printf 'Finish by typing %s on a line of its own (Ctrl-D also finishes).\n\n' "$PROMPT_DELIMITER" >&2
    buf=""; have_data=0
    while IFS= read -r -u "$INPUT_FD" line || [[ -n "$line" ]]; do
      [[ "$line" == "$PROMPT_DELIMITER" || "$line" == "$PROMPT_DELIMITER"$'\r' ]] && break
      buf+="$line"$'\n'
      have_data=1
    done
    ((have_data)) && buf=${buf%$'\n'}   # drop only the newline that preceded END

    if is_blank "$buf"; then
      warn "The prompt is empty."
      while true; do
        ask "Type 'r' to enter a prompt again, or 'd' to use the default Viking prompt instead" "r" || die "Input closed."
        case "$REPLY_VALUE" in
          [Rr]) continue 2 ;;
          [Dd]) return 10 ;;
          *) warn "Please type r or d." ;;
        esac
      done
    fi
    if ((${#buf} > MAX_PROMPT_CHARS)); then
      warn "That prompt is ${#buf} characters; the limit is $MAX_PROMPT_CHARS (small local models degrade with huge prompts). Please shorten it."
      continue
    fi
    CUSTOM_PROMPT=$buf
    return 0
  done
}

read_prompt_file() {  # exact file contents (minus one trailing newline) -> CUSTOM_PROMPT
  local f=$1
  [[ -f "$f" && -r "$f" ]] || die "Prompt file not found or unreadable: $f"
  [[ "$(wc -c <"$f")" -le $((MAX_PROMPT_CHARS * 4)) ]] || die "Prompt file is too large: $f"
  CUSTOM_PROMPT=$(cat -- "$f"; printf x)    # sentinel keeps trailing newlines intact
  CUSTOM_PROMPT=${CUSTOM_PROMPT%x}
  if [[ "$CUSTOM_PROMPT" == *$'\r\n' ]]; then CUSTOM_PROMPT=${CUSTOM_PROMPT%$'\r\n'}
  else CUSTOM_PROMPT=${CUSTOM_PROMPT%$'\n'}; fi
  is_blank "$CUSTOM_PROMPT" && die "Prompt file is empty: $f" "Provide a non-empty file or use --prompt-mode default."
  ((${#CUSTOM_PROMPT} <= MAX_PROMPT_CHARS)) || die "Prompt file exceeds $MAX_PROMPT_CHARS characters: $f"
  return 0
}

choose_prompt_mode() {
  PROMPT_MODE=""
  if ((KEEP_PROMPT)); then
    existing_role_present || die "--keep-prompt was given but no Viking role exists yet." "Run ./install.sh without --keep-prompt."
    PROMPT_MODE=keep
  elif [[ -n "$PROMPT_MODE_ARG" ]]; then
    PROMPT_MODE=$PROMPT_MODE_ARG
  elif [[ -n "$INPUT_FD" ]]; then
    if existing_role_present; then
      info "An existing Viking role was found (${OLD_PROMPT_MODE:-unknown} prompt). Choose again below: the old role is"
      info "REPLACED by your new choice. Nothing from it is kept or merged."
    fi
    prompt_menu
  elif existing_role_present; then
    PROMPT_MODE=keep      # non-interactive re-run without prompt flags: leave the role alone
  else
    PROMPT_MODE=default   # non-interactive fresh install without prompt flags
  fi
}

# Exactly ONE of the two prompts ends up in FINAL_SYSTEM_PROMPT. The branches are
# separate; neither reads the other's variable, and there is no concatenation.
build_final_prompt() {
  FINAL_SYSTEM_PROMPT=""
  local rc=0
  case "$PROMPT_MODE" in
    custom)
      if [[ -n "$PROMPT_FILE_ARG" ]]; then
        read_prompt_file "$PROMPT_FILE_ARG"
      else
        read_custom_prompt || rc=$?
      fi
      if ((rc == 10)); then
        # User explicitly abandoned the (empty) custom prompt for the default option.
        CUSTOM_PROMPT=""
        PROMPT_MODE=default
        FINAL_SYSTEM_PROMPT=$DEFAULT_SYSTEM_PROMPT
      else
        FINAL_SYSTEM_PROMPT=$CUSTOM_PROMPT
      fi
      ;;
    default)
      FINAL_SYSTEM_PROMPT=$DEFAULT_SYSTEM_PROMPT
      ;;
    keep)
      return 0
      ;;
    *)
      die "Internal error: unknown prompt mode '$PROMPT_MODE'."
      ;;
  esac
  CUSTOM_PROMPT=""   # make sure no stale custom text can leak into later steps
}

# Role JSON is written by Python's json module from a file, so the prompt never
# passes through shell evaluation, printf formats, or argument parsing.
write_role() {
  [[ "$PROMPT_MODE" == keep ]] && { ROLE_STATUS=kept; return 0; }
  local src="$TMP_DIR/prompt.txt" role_file="$ROLE_DIR/$ROLE_NAME.json"
  printf '%s' "$FINAL_SYSTEM_PROMPT" >"$src"
  chmod 600 "$src"

  # A viking.json that predates VikingAI (no config file) is not ours: keep a backup.
  if [[ -f "$role_file" && ! -f "$CONFIG_FILE" ]]; then
    cp -p -- "$role_file" "$role_file.bak.$(date +%Y%m%d%H%M%S)"
    warn "An unrelated '$ROLE_NAME' role already existed; backed it up next to the original."
  fi

  "$VENV_DIR/bin/python" - "$src" "$ROLE_DIR" "$ROLE_NAME" <<'PY' || die "Writing the Viking role failed." \
    "Check that the prompt is valid UTF-8 text and that $ROLE_DIR is writable."
import json, os, sys, tempfile
src, role_dir, name = sys.argv[1:4]
with open(src, "r", encoding="utf-8", newline="") as fh:
    text = fh.read()
payload = json.dumps({"name": name, "role": text})
fd, tmp = tempfile.mkstemp(dir=role_dir, prefix=".viking-", suffix=".tmp")
try:
    with os.fdopen(fd, "w", encoding="utf-8") as out:
        out.write(payload)
    os.chmod(tmp, 0o600)
    os.replace(tmp, os.path.join(role_dir, name + ".json"))
except BaseException:
    try:
        os.unlink(tmp)
    except FileNotFoundError:
        pass
    raise
PY
  ROLE_STATUS=written
}

# Prove the role on disk contains exactly the selected prompt and nothing else.
verify_role() {
  [[ "$PROMPT_MODE" == keep ]] && return 0
  local src="$TMP_DIR/prompt.txt" shown="$TMP_DIR/shown.txt"
  "$VENV_DIR/bin/python" - "$src" "$ROLE_DIR/$ROLE_NAME.json" "$ROLE_NAME" <<'PY' \
    || die "Role verification FAILED: the role file does not contain exactly the selected prompt." \
         "Remove $ROLE_DIR/$ROLE_NAME.json and re-run ./install.sh"
import json, sys
src, role_file, name = sys.argv[1:4]
with open(src, "r", encoding="utf-8", newline="") as fh:
    expected = fh.read()
with open(role_file, "r", encoding="utf-8") as fh:
    data = json.load(fh)
assert set(data) == {"name", "role"}, "unexpected keys: %s" % sorted(data)
assert data["name"] == name, "wrong role name"
assert data["role"] == expected, "role text differs from the selected prompt"
PY
  # Second opinion through ShellGPT itself (version-accurate): --show-role.
  env -i HOME="$HOME" PATH="/usr/local/bin:/usr/bin:/bin" LANG="${LANG:-C.UTF-8}" TERM=dumb NO_COLOR=1 \
    OPENAI_API_KEY="viking-local-placeholder" ROLE_STORAGE_PATH="$ROLE_DIR" \
    "$SGPT" --show-role "$ROLE_NAME" </dev/null >"$shown" 2>/dev/null \
    || die "ShellGPT could not load the Viking role." "Run: '$SGPT' --show-role $ROLE_NAME"
  "$VENV_DIR/bin/python" - "$src" "$shown" <<'PY' \
    || die "ShellGPT shows different text than the saved prompt." "Re-run ./install.sh"
import sys
with open(sys.argv[1], "r", encoding="utf-8", newline="") as fh:
    expected = fh.read()
with open(sys.argv[2], "r", encoding="utf-8", newline="") as fh:
    shown = fh.read()
assert shown == expected + "\n", "ShellGPT output differs from the stored prompt"
PY
  ok "Role verified: '$ROLE_NAME' contains only the selected prompt (${#FINAL_SYSTEM_PROMPT} characters)"
}

